let nextId = 1;

function p(spec) {
  const id = `P${String(nextId).padStart(3, "0")}`;
  nextId += 1;
  const pool = IMG[spec.imgKey];
  const offset = spec.imgOffset ?? 0;
  const gallery = [0, 1, 2, 3].map((i) => img(pool[(i + offset) % pool.length]));

  return {
    id,
    slug: slugify(spec.name),
    name: spec.name,
    brand: spec.brand,
    gender: spec.gender,
    category: spec.category,
    subCategory: spec.subCategory,
    collection: spec.collection,
    season: spec.season,
    price: spec.price,
    discount: spec.discount ?? 0,
    rating: spec.rating,
    reviewCount: spec.reviewCount,
    featured: Boolean(spec.featured),
    newArrival: Boolean(spec.newArrival),
    bestSeller: Boolean(spec.bestSeller),
    image: gallery[0],
    gallery,
    description: spec.description,
    colors: spec.colors,
    sizes: spec.sizes,
    stock: spec.stock,
    createdAt: spec.createdAt,
    sku: `OX-${spec.category.slice(0, 2).toUpperCase()}-${id}`,
  };
}

